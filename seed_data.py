def seed_words(db: Session) -> None:
    """Add any lesson item that is not in the database yet."""
    existing = {(w.language, w.category, w.text) for w in db.query(models.Word).all()}
    added = 0

    for language, items in LESSONS.items():
        for category, text, translation, pronunciation, note in items:
            if (language, category, text) in existing:
                continue
            db.add(
                models.Word(
                    language=language,
                    category=category,
                    text=text,
                    translation=translation,
                    pronunciation=pronunciation,
                    note=note,
                )
            )
            added += 1

    if added:
        db.commit()